export function getRegionContent(id) {
  const content = id == null || id === COUNTRY.id ? countryContent : regionsContent[id] ?? {}
  return {
    tagline: content.tagline ?? '',
    facts: (content.facts ?? []).filter((f) => f.label || f.value),
    eras: Object.fromEntries(
      ERAS.map(({ key }) => {
        const era = content.eras?.[key] ?? {}
        return [key, { text: era.text ?? '', highlights: (era.highlights ?? []).filter(Boolean), image: era.image ?? '' }]
      })
    ),
  }
}
